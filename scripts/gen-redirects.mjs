// Emit public/_redirects so the reverse ordering of every compare pair 301s
// to its canonical alphabetically-sorted URL. compare/[slug].astro promises
// this redirect; without it, reverse/legacy inbound URLs 404. Regenerated
// pre-build so it can never drift from the vendor set. Astro copies
// public/_redirects into dist/, which is the assets directory served by
// Cloudflare Workers static assets (wrangler.jsonc); Workers static assets
// honour _redirects up to a 2,000 static-rule limit, well above our 105.
import { readdirSync, writeFileSync } from 'node:fs';
import { basename } from 'node:path';

const dir = new URL('../src/content/vendors/', import.meta.url).pathname;
// Default sort matches comparePath()'s [a, b].sort() and the getStaticPaths
// localeCompare ordering for these lowercase kebab slugs.
const slugs = readdirSync(dir)
  .filter((f) => f.endsWith('.yaml'))
  .map((f) => basename(f, '.yaml'))
  .sort();

const lines = [
  '# Generated by scripts/gen-redirects.mjs. Do not edit by hand.',
  '# Reverse-ordered compare pairs 301 to their canonical (sorted) URL.',
];
for (let i = 0; i < slugs.length; i++) {
  for (let j = i + 1; j < slugs.length; j++) {
    const canonical = `/compare/${slugs[i]}-vs-${slugs[j]}/`;
    const reverse = `/compare/${slugs[j]}-vs-${slugs[i]}/`;
    lines.push(`${reverse} ${canonical} 301`);
  }
}

const out = new URL('../public/_redirects', import.meta.url).pathname;
writeFileSync(out, `${lines.join('\n')}\n`);
console.log(
  `✓ public/_redirects (${slugs.length} vendors -> ${lines.length - 2} redirects)`,
);
