// Generates public/_redirects for Cloudflare (Workers static assets honour it,
// and Astro copies public/ verbatim into dist/). One class of 301, for routes
// that existed in v1 but not v2 (SPEC piece 11):
//
//   /compare/b-vs-a/     — v1 generated BOTH orderings of every pair; v2
//                          generates one canonical page per unordered pair
//                          (alphabetical by slug — see compare.mjs /
//                          compare/[slug].astro). Every reverse ordering
//                          301s to its canonical URL so no inbound link
//                          404s and duplicate content is consolidated.
//
// /compare/ itself is a real page again (v2.2 two-vendor picker), so it must
// NOT carry a redirect here — a _redirects rule would shadow the static page.
//
// Run: node scripts/gen-redirects.mjs  (also wired as `npm run gen:redirects`)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const vendorsDir = join(root, 'src/content/vendors');

const slugs = readdirSync(vendorsDir)
  .filter((f) => f.endsWith('.yaml'))
  .map((f) => {
    const m = readFileSync(join(vendorsDir, f), 'utf8').match(
      /^slug:\s*(.+)$/m,
    );
    if (!m) throw new Error(`no slug field in ${f}`);
    return m[1].trim();
  })
  // Match the canonical ordering used by compare/[slug].astro getStaticPaths.
  .sort((a, b) => a.localeCompare(b));

const lines = [
  '# Generated by scripts/gen-redirects.mjs — do not edit by hand.',
  '# 301s for routes removed in v2 (SPEC piece 11).',
  '',
  '# Reverse-ordered compare pairs -> canonical (alphabetical-by-slug) page.',
];

for (let i = 0; i < slugs.length; i++) {
  for (let j = i + 1; j < slugs.length; j++) {
    const canonical = `/compare/${slugs[i]}-vs-${slugs[j]}/`;
    const reverse = `/compare/${slugs[j]}-vs-${slugs[i]}/`;
    lines.push(`${reverse}  ${canonical}  301`);
  }
}

writeFileSync(join(root, 'public/_redirects'), `${lines.join('\n')}\n`);
const pairCount = (slugs.length * (slugs.length - 1)) / 2;
console.log(
  `wrote public/_redirects: ${pairCount} reverse-pair redirects (${slugs.length} vendors)`,
);
